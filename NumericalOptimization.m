clear
clc

load AnalyticalResults.mat

P = BeamParameters();

Data = BeamData();

Cases = {'Cantilever','SimplySupported'};

Optimization = struct();

%% Compute SMA recovery strain at prescribed temperature

for k = 1:length(Data.Temperatures)

    T = Data.Temperatures(k);

    epsT = SMARecoveryStrain( ...
        T,...
        Data.AsTemp,...
        Data.AfTemp,...
        Data.epsL);

    fprintf('\n');
    fprintf('====================================\n');
    fprintf('Temperature = %.1f C\n',T);
    fprintf('====================================\n');

    for i = 1:length(Cases)

        BC = Cases{i};

        fprintf('\n');
        fprintf('=========================================\n');
        fprintf('%s\n',BC);
        fprintf('=========================================\n');

        Curv = Curvature.(BC);

        J = ObjectiveFunction(P,Curv);

        Jfun = matlabFunction( ...
            J,...
            'Vars',...
            { ...
            P.x1,...
            P.l,...
            P.L,...
            P.Eb,...
            P.Ib,...
            P.Es,...
            P.Is,...
            P.As,...
            P.d,...
            P.epsT,...
            P.q0,...
            P.k0});

        fun = @(X) Jfun( ...
            X(1),...
            X(2),...
            Data.L,...
            Data.Eb,...
            Data.Ib,...
            Data.Es,...
            Data.Is,...
            Data.As,...
            Data.d,...
            epsT,...
            Data.q0,...
            Data.k0);

        A = [1 1];
        b = Data.L;

        lb = [0 Data.lmin];
        ub = [Data.L Data.lmax];

        X0 = [Data.x10 Data.l0];

        options = optimoptions( ...
            'fmincon',...
            'Algorithm','sqp',...
            'Display','iter',...
            'MaxFunctionEvaluations',10000,...
            'OptimalityTolerance',1e-12,...
            'StepTolerance',1e-12);

        [Xopt,Jmin] = fmincon( ...
            fun,...
            X0,...
            A,...
            b,...
            [],...
            [],...
            lb,...
            ub,...
            [],...
            options);

        Optimization.(BC).Temperature(k) = T;

        Optimization.(BC).epsT(k) = epsT;

        Optimization.(BC).Xopt(k,:) = Xopt;

        Optimization.(BC).Jmin(k) = Jmin;

        fprintf('\n');
        fprintf('Optimal SMA location x1 = %.6f\n',Xopt(1));

        fprintf('Optimal SMA length   l  = %.6f\n',Xopt(2));

        fprintf('Minimum Objective    = %.6e\n',Jmin);

    end

end

save('OptimizationResults.mat','Optimization');

PostProcessing(Optimization);
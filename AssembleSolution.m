function Results = AssembleSolution(P,Curvature,Rotation,Displacement,Constants)

old = [ ...
    P.C3 ...
    P.C4 ...
    P.C5 ...
    P.C6 ...
    P.C7 ...
    P.C8];

new = [ ...
    Constants.C3 ...
    Constants.C4 ...
    Constants.C5 ...
    Constants.C6 ...
    Constants.C7 ...
    Constants.C8];

Results.kappa1 = simplify(Curvature.kappa1);
Results.kappa2 = simplify(Curvature.kappa2);
Results.kappa3 = simplify(Curvature.kappa3);

Results.theta1 = simplify(subs(Rotation.theta1,old,new));
Results.theta2 = simplify(subs(Rotation.theta2,old,new));
Results.theta3 = simplify(subs(Rotation.theta3,old,new));

Results.w1 = simplify(subs(Displacement.w1,old,new));
Results.w2 = simplify(subs(Displacement.w2,old,new));
Results.w3 = simplify(subs(Displacement.w3,old,new));

x = P.x;

Results.kappa = piecewise( ...
    x < P.x1, Results.kappa1,...
    x <= P.x1 + P.l, Results.kappa2,...
    Results.kappa3);

Results.theta = piecewise( ...
    x < P.x1, Results.theta1,...
    x <= P.x1 + P.l, Results.theta2,...
    Results.theta3);

Results.w = piecewise( ...
    x < P.x1, Results.w1,...
    x <= P.x1 + P.l, Results.w2,...
    Results.w3);

end
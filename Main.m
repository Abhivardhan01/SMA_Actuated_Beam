clear
clc

P = BeamParameters();

Forces = InternalForces(P);


% Cantilever Beam

Curvature.Cantilever = ...
    CurvatureSolution(P,Forces.Cantilever);

Rotation.Cantilever = ...
    RotationSolution(P,Curvature.Cantilever);

Displacement.Cantilever = ...
    DisplacementSolution(P,Rotation.Cantilever);

Constants.Cantilever = ...
    SolveIntegrationConstants( ...
        P,...
        Rotation.Cantilever,...
        Displacement.Cantilever,...
        'Cantilever');

Results.Cantilever = ...
    AssembleSolution( ...
        P,...
        Curvature.Cantilever,...
        Rotation.Cantilever,...
        Displacement.Cantilever,...
        Constants.Cantilever);

% Simply Supported Beam

Curvature.SimplySupported = ...
